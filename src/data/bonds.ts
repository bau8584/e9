// 호감도 단계별 관계 문구. 전부 제작진이 지어낸 각색이며 인물의 실제 발언이 아니다.
// 싯다르타는 더 다정해질 뿐 친한 척하거나 망가지지 않는다. 연애와 니체의 병은 소재로 쓰지 않는다.
// 단계가 오를수록 호칭이 바뀌고, 먼저 챙기고, 자기 얘기를 꺼낸다.
// {name}은 닉네임, {book}은 사용자가 가장 최근에 등록한 책 제목으로 바뀐다.
export interface BondStage {
  /** 홈과 DM에 보이는 관계 이름 */
  title: string;
  /** 지금 관계가 어떤 사이인지 한 줄로 */
  description: string;
  /** 홈에서 최애가 건네는 한마디 */
  greeting: string;
  /** DM을 열 때 이 단계에서만 먼저 건네는 말. 0단계는 없다. */
  opener?: string;
  /** 가장 최근 등록한 책에 대한 반응 */
  bookReaction: string;
  /** 이 단계에 오를 때 한 번 나오는 장면의 대사. 4~6줄, 0단계는 비어 있다. */
  moment: string[];
  /** 이 단계에서 인물이 나를 부르는 호칭 틀. 예: "거기 너", "{name}", "내 친구 {name}" */
  callName?: string;
  /** 이 단계가 아직 잠겨 있을 때 보여 주는 암시 한 줄. 0단계는 없다. */
  teaser?: string;
}

