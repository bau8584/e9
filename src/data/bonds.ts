/** 날짜(YYYY-MM-DD)를 날 번호로. 하루마다 1씩 늘어 인사를 날마다 바꿔 쓰는 데 쓴다. */
export function dayNumber(dateKey: string): number {
  const [y, m, d] = dateKey.split('-').map(Number);
  return Math.round(Date.UTC(y, (m || 1) - 1, d || 1) / 86_400_000);
}

/** 홈 인사 한 줄. 처음 온 날(함께한 날 1일 이하)에 0단계면 첫인사, 아니면 그 단계 인사를 날짜에 따라 돌려 쓴다. */
export function greetingOf(stage: BondStage, days: number, dateKey: string): string {
  if (days <= 1 && stage.firstGreeting) return stage.firstGreeting;
  const pool = stage.greetings;
  return pool[((dayNumber(dateKey) % pool.length) + pool.length) % pool.length];
}
